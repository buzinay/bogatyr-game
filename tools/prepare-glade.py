"""Build static delivery copies and data from supplied graphics and specification."""
from pathlib import Path
from PIL import Image
import json,re,unicodedata,shutil
ROOT=Path(__file__).resolve().parent.parent
out=ROOT/'dist/assets/glade';out.mkdir(parents=True,exist_ok=True)
layers=json.loads((ROOT/'qa/glade-layers/layers.json').read_text(encoding='utf-8'))
manifest=[]
def layer(index,name,z):
    if isinstance(index,str):
        matches=[r for r in layers if r['name']==index]
        if len(matches)!=1:raise ValueError('Expected one PSD layer: '+index)
        index=matches[0]['index']
    r=layers[index];src=ROOT/'qa/glade-layers'/r['file'];shutil.copyfile(src,out/(name+'.png'))
    l,t,right,b=r['crop'];s=dict(image='assets/glade/'+name+'.png',x=l,y=t,width=right-l,height=b-t,z=z)
    manifest.append(dict(**s,source='Поляна/Поляна_собери богатыря.psd',layerIndex=index,layerName=r['name']))
    return s
def png(folder,name,dest,z=0):
    src=next(p for p in (ROOT/folder).glob('*.png') if unicodedata.normalize('NFC',p.name)==unicodedata.normalize('NFC',name))
    im=Image.open(src).convert('RGBA');box=im.getbbox();im.crop(box).save(out/(dest+'.png'))
    l,t,r,b=box;s=dict(image='assets/glade/'+dest+'.png',x=l,y=t,width=r-l,height=b-t,z=z)
    manifest.append(dict(**s,source=str(src.relative_to(ROOT))))
    return s
bg=png('Поляна','Поляна_фон.png','background')
hero=layer('Богатырь Одетый','hero-base',40)
front=[layer(4,'terrain-front',15),layer(9,'branch-front',25),layer(14,'house-front',25),layer(18,'tree-front',25),layer('Куст Правый','bush-right',35),layer('Куст Левый','bush-left',35)]
ids=['sword','spear','shield','horse','plough','rein','sun','sabre','mace','raspberry_1','raspberry_2']
hidden={'sword':(21,30),'spear':(6,20),'shield':(32,30),'horse':(27,28),'plough':(29,29),'rein':(8,20),'sun':(2,10),'sabre':(17,20),'mace':(19,30),'raspberry_1':(24,30),'raspberry_2':(25,30)}
cards=['Меч','Копье','Щит','Конь_большой','Соха','Повод','Солнце','Сабля','Булава','Малина','Малина']
items={};hit={}
for id,title in zip(ids,cards):
    h=layer(hidden[id][0],id+'-hidden',hidden[id][1]);card=png('Богатырь исходные картинки' if id=='sabre' else 'Поляна',title+' карточка.png',id+'-card')
    items[id]=dict(hidden=[h],worn=[],cardImage=card['image'],sound=None)
    # Visible alpha minus foreground; 4 px strips give compact editable polygons.
    im=Image.open(ROOT/'dist'/h['image']).convert('RGBA');mask=Image.new('L',(1600,1200));mask.paste(im.getchannel('A'),(h['x'],h['y']))
    import PIL.ImageChops as chops
    for f in front+[hero]:
        if f['z']<=h['z']:continue
        cover=Image.new('L',(1600,1200));cover.paste(Image.open(ROOT/'dist'/f['image']).getchannel('A'),(f['x'],f['y']));mask=chops.subtract(mask,cover)
    polygons=[]
    for y in range(h['y'],min(1200,h['y']+h['height']),4):
        band=mask.crop((0,y,1600,min(y+4,1200)));xs=[x for x in range(1600) if band.crop((x,0,x+1,band.height)).getextrema()[1]>24]
        if xs:
            start=prev=xs[0]
            for x in xs[1:]+[2000]:
                if x>prev+1:
                    polygons.append([[start,y],[prev+1,y],[prev+1,min(y+4,1200)],[start,min(y+4,1200)]]);start=x
                prev=x
    if not polygons:raise ValueError('Invisible hideout '+id)
    hit[id]=polygons
items['sabre']['worn']=[layer('Сабля В Правой','sabre-worn',42)]
items['spear']['worn']=[layer('Копье В Правой','spear-worn',42)]
items['mace']['worn']=[layer('Булава Снятая','mace-worn',39)]
items['sword']['worn']=[layer('Ножны','sword-sheath',41),layer('Меч В Руке','sword-worn',42)]
items['shield']['worn']=[layer('Слой 47','shield-back',39),layer('Ручки Щита','shield-handles',41)]
# Existing, customer-selected audio; short copies generated by shorten-izba-audio.cjs.
audioids=dict(sword='1485',spear='432148',shield='7118',horse='85',plough='27585',rein='46399',sun='2344',sabre='1487',mace='820',raspberry_1='383725',raspberry_2='383725')
for id,num in audioids.items():
    src=next(p for p in (ROOT/'Звуки').iterdir() if re.search('-'+num+r'\.(wav|mp3)$',p.name))
    shutil.copyfile(src,ROOT/'dist/assets/audio'/src.name);items[id]['sound']='assets/audio/'+src.name
config=dict(canvas=dict(width=1600,height=1200),mobileDetailWidth=800,background=bg,layers=front+[hero],items=items,hitAreas=hit)
(ROOT/'dist/config/glade.json').write_text(json.dumps(config,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
spec=(ROOT/'BOGATYR_GAME_SPEC.md').read_text(encoding='utf-8');content=[]
titles=dict(zip(ids,['Меч','Копьё','Щит','Конь богатырский','Соха','Повод','Солнце','Сабля','Булава','Малина','Малина']))
for id in ids:
    section=re.search(r'^### '+('raspberry_1 / raspberry_2' if id.startswith('raspberry') else id)+r'\s*\n(.*?)(?=^### |^## |\Z)',spec,re.M|re.S).group(1)
    desc=re.search(r'\*\*Определение:\*\* (.*)',section).group(1)
    title=re.search(r'\*\*Читать ещё — (.*?)\*\*',section).group(1)
    excerpt='\n'.join(line[2:] if line.startswith('> ') else '' for line in section.splitlines() if line.startswith('>'))
    link=re.search(r'Источник: <([^>]+)>',section).group(1)
    content.append(dict(id=id,title=titles[id],scene='glade',description=desc,contentStatus='customer_supplied',moreReading=dict(title=title,excerpt=excerpt,sourceLabel=link.split('/')[2],sourceUrl=link,status='customer_supplied',sourceVerification='not_checked'),actionLabel='Выбрать оружие' if id in ['sword','sabre','mace','spear'] else 'Взять' if id=='shield' else None))
(ROOT/'dist/content/glade.json').write_text(json.dumps(content,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
(ROOT/'GLADE_ASSET_MANIFEST.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print('Prepared 11 hideouts, 4 weapon choices, shield, foreground and exact supplied card texts.')
import runpy
runpy.run_path(str(ROOT/'tools/place-glade-items.py'))
